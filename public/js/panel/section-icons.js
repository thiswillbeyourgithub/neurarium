/**
 * The icon key of one panel section: its explicit `data-icon`, else its tour anchor.
 * @param {HTMLElement} sec
 * @returns {?string}
 */
export function sectionIconKey(sec) {
  return sec.dataset.icon || sec.dataset.tourSec || null;
}

/**
 * The decorative `<svg class="sec-icon">` for a section key, or null when it has none.
 * @param {?string} key
 * @returns {?SVGSVGElement}
 */
export function sectionIcon(key) {
  const inner = key && GLYPHS[SECTION_ICONS[key]];
  if (!inner) return null;
  const svg = document.createElementNS(SVG_NS, "svg");
  for (const [k, v] of Object.entries({
    class: "sec-icon", viewBox: "0 0 24 24", fill: "none", stroke: "currentColor",
    "stroke-width": "2", "stroke-linecap": "round", "stroke-linejoin": "round",
    "aria-hidden": "true", focusable: "false",
  })) svg.setAttribute(k, v);
  svg.innerHTML = inner;
  return svg;
}
